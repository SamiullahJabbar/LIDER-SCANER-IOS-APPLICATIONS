// ============================================================================
// PRODUCTION-READY Scan Export Service
// Converts point cloud data to standard 3D formats (OBJ, PLY, XYZ, CSV)
//
// Features:
//   • OBJ export with vertex colors
//   • PLY export (binary + ASCII) with confidence data
//   • XYZ plain text export
//   • CSV export for spreadsheet analysis
//   • Metadata JSON sidecar
//   • Share via system share sheet (share_plus)
//   • File size estimation
//
// NO backend dependency — all exports are local-only
// ============================================================================
